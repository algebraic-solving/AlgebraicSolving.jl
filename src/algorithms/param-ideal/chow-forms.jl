@doc Markdown.doc"""
    chow_form(I::ParametricIdeal{K}, S::MPolyRing{K}; <keyword arguments>) -> MPolyRingElem{K}

Computes the monic Chow form of the zero-dimensional variety defined by the parametric ideal `I`.

Let `I` be generated by `f_1,…,f_s` in `K[x_1,…,x_n]`,
where `K = QQ(y_1,…,y_t)` is the field of rational functions in the parameters,
such that `I` is zero-dimensional over `K`.
Let `δ = dim_K K[x]/I` and let `L_g` denote the multiplication by `g` on `K[x]/I`.
By default (`reduced=true`), this returns the monic Chow form of the reduced variety `V(I)`,

``C(u_0,u_1,…,u_n) = \prod_{\zeta} (u_0 + u_1\zeta_1 + \dots + u_n\zeta_n),``

where the product runs over the distinct zeros `ζ` of `I` in an algebraic closure of `K`.
With `reduced=false`, it returns instead

``C(u_0,u_1,…,u_n) = \det(u_0 \cdot \mathrm{Id} + \sum_{k=1}^n u_k L_{x_k}) = \prod_{\zeta} (u_0 + u_1\zeta_1 + \dots + u_n\zeta_n)^{\mu_\zeta},``

where the zeros are counted with their multiplicities `μ_ζ`.
In both cases, `C` is homogeneous in `(u_0,…,u_n)` and the coefficient of the highest power of `u_0` is `1`.
Its degree is the number of distinct zeros of `I` for the reduced Chow form,
and the number of zeros counted with multiplicity, `Σ_ζ μ_ζ = δ`, otherwise.

The result lies in `S`, which must be a polynomial ring over `K` in `n + 1` variables,
read as `u_0, u_1, …, u_n` in this order, where `u_k` corresponds to the `k`-th variable of `I`.

With `primitive=true`, it returns instead the primitive Chow form `C*`:
the unique multiple of `C` whose coefficients lie in `ZZ[y]` without common factor in `ZZ[y]`,
and such that `a = C*(1,0,…,0)`, the coefficient of `u_0^δ`, has a positive leading coefficient
(w.r.t. the monomial ordering of the parameter ring).
Then `C* = a·C`. It lies in the same ring as `C`.

The `algorithm` keyword selects how the Chow form is computed:
- `:det`: as the determinant of `u_0 \cdot \mathrm{Id} + Σ_k u_k M_{x_k}` over `K[u_0,…,u_n]`, from the parametric multiplication matrices `M_{x_k}`.
- `:trace` (default): from the same multiplication matrices and the multivariate Newton identities on their traces; usually faster as `δ` or `n` grow.

# Arguments
- `primitive::Bool=false`: whether to return the primitive Chow form `C*` instead of the monic one.
- `reduced::Bool=true`: whether to return the Chow form of the reduced variety; otherwise, count the zeros with their multiplicities.
- `algorithm::Symbol=:trace`: the algorithm to use, either `:det` or `:trace` (see above).
- `retry::Int=10`: the maximum number of consecutive failures allowed when computing the multiplication matrices or interpolating the coefficients.
- `nr_thrds::Int=1`: the number of threads to use for parallel computations.
- `worker_pool::AbstractWorkerPool=default_worker_pool()`: the worker pool to use for parallel computations.
- `show_progress::Bool=false`: whether to show a progress bar.

# Examples
```jldoctest
julia> using AlgebraicSolving

julia> R, (y,) = polynomial_ring(QQ, [:y]);

julia> S, (x1, x2) = polynomial_ring(fraction_field(R), [:x1, :x2], internal_ordering=:degrevlex);

julia> I = ParametricIdeal([x1^2, x2 - y]);

julia> T, _ = polynomial_ring(fraction_field(R), [:u0, :u1, :u2]);

julia> chow_form(I, T)
u0 + y*u2

julia> chow_form(I, T; reduced=false)
u0^2 + 2*y*u0*u2 + y^2*u2^2

julia> S, (x,) = polynomial_ring(fraction_field(R), [:x], internal_ordering=:degrevlex);

julia> I = ParametricIdeal([(2*y + 2)*x^2 + y*x + y]);

julia> T, _ = polynomial_ring(fraction_field(R), [:u0, :u1]);

julia> chow_form(I, T)
u0^2 - (1//2*y)//(y + 1)*u0*u1 + (1//2*y)//(y + 1)*u1^2

julia> chow_form(I, T; primitive=true)
(2*y + 2)*u0^2 - y*u0*u1 + y*u1^2
```
"""
function chow_form(
    I::ParametricIdeal{K},
    S::MPolyRing{K};
    primitive::Bool=false,
    reduced::Bool=true,
    algorithm::Symbol=:trace,
    retry::Int=10,
    nr_thrds::Int=1,
    worker_pool::AbstractWorkerPool=default_worker_pool(),
    show_progress::Bool=false
) where {K<:FracFieldElem}
    n = I.num_vars
    base_ring(S) == I.base_frac_field || throw(ArgumentError("S must be a polynomial ring over the coefficient field of I."))
    number_of_variables(S) == n + 1 || throw(ArgumentError("S must have $(n + 1) variables, one more than I."))
    kw = (retry=retry, nr_thrds=nr_thrds, worker_pool=worker_pool, show_progress=show_progress)
    algorithm in (:trace, :det) || throw(ArgumentError("Unknown algorithm $(algorithm), expected :trace or :det."))
    if reduced && !I.radicalize
        I = ParametricIdeal(I.gens; sats=I.sats, num_vars=I.num_vars, prefer_gb=I.prefer_gb, radicalize=true, gens_alt=I.gens_alt)
    end
    C = algorithm == :trace ? _chow_form_by_traces(I, S; kw...) : _chow_form_by_det(I, S; kw...)
    primitive || return C
    C = divexact(C, content(C))
    c = reduce(gcd, [content(numerator(a)) for a in coefficients(C)])
    a = coeff(C, [total_degree(C); zeros(Int, n)])
    if leading_coefficient(numerator(a)) < 0
        c = -c
    end
    divexact(C, base_ring(C)(c))
end

# We can compute the monic Chow form as det(u_0·Id + Σ_k u_k·M_{x_k}) over K[u_0,…,u_n],
# from the parametric multiplication matrices.
function _chow_form_by_det(
    I::ParametricIdeal{K},
    S::MPolyRing;
    retry::Int=10,
    nr_thrds::Int=1,
    worker_pool::AbstractWorkerPool=default_worker_pool(),
    show_progress::Bool=false
) where {K<:FracFieldElem}
    R = parent(I.gens[1])
    xs = [gens(R)[findfirst(==(s), symbols(R))] for s in I.symbols]
    M = [multiplication_matrix(I, x; retry=retry, nr_thrds=nr_thrds, worker_pool=worker_pool, show_progress=show_progress) for x in xs]
    u = gens(S)
    A = u[1] * identity_matrix(S, nrows(M[1]))
    for k in eachindex(M)
        A += u[k+1] * map(c -> S(c), M[k])
    end
    det(A)
end

function _multinomial(α::Vector{Int})::ZZRingElem
    c = ZZ(1)
    s = 0
    for a in α
        s += a
        c *= binomial(ZZ(s), ZZ(a))
    end
    c
end

# We can also compute the monic Chow form from the traces of the parametric multiplication matrices
# and the multivariate Newton identities.
function _chow_form_by_traces(
    I::ParametricIdeal{K},
    S::MPolyRing;
    retry::Int=10,
    nr_thrds::Int=1,
    worker_pool::AbstractWorkerPool=default_worker_pool(),
    show_progress::Bool=false
) where {K<:FracFieldElem}
    # We compute the exponent vectors of the standard monomials,
    # in the same order as the one used by multiplication matrices.
    if I.prefer_gb
        gb = groebner_basis(I; retry=retry, nr_thrds=nr_thrds, worker_pool=worker_pool, show_progress=show_progress)
    else
        gb = groebner_basis(I, QQ.(I.shift); worker_pool=worker_pool)
    end
    β = [exponent_vector(b, 1) for b in _monomial_basis(gb)]
    δ = length(β)
    if δ == 0
        return one(S)
    end
    R = parent(I.gens[1])
    xs = [gens(R)[findfirst(==(s), symbols(R))] for s in I.symbols]
    M = [multiplication_matrix(I, x; retry=retry, nr_thrds=nr_thrds, worker_pool=worker_pool, show_progress=show_progress) for x in xs]
    if any(m -> nrows(m) != δ, M)
        error("The multiplication matrices and the standard monomials have inconsistent sizes.")
    end
    # We compute the traces τ of the multiplication maps by the standard monomials,
    # with τ_i = Tr(L_{b_i}) for the standard monomial b_i = x^{β_i}.
    # As the standard monomials form an order ideal,
    # every b_i ≠ 1 is x_k·b_j for some earlier b_j, so that M_{b_i} = M[k]·M_{b_j}.
    F = base_ring(M[1])
    @assert all(iszero, β[1])
    Mb = Vector{typeof(M[1])}(undef, δ)
    Mb[1] = identity_matrix(F, δ)
    τ = Vector{elem_type(F)}(undef, δ)
    τ[1] = F(δ)
    for i in 2:δ
        found = false
        for k in eachindex(β[i])
            β[i][k] == 0 && continue
            γ = copy(β[i])
            γ[k] -= 1
            j = findfirst(==(γ), β)
            if !isnothing(j) && j < i
                Mb[i] = M[k] * Mb[j]
                τ[i] = tr(Mb[i])
                found = true
                break
            end
        end
        found || error("The standard monomials do not form an order ideal.")
    end
    # We write C(1,u) = Σ_m C_m(u) with C_m homogeneous of degree m.
    # With the power sums P_j(u) = Tr((u·L_x)^j) = Σ_{|α|=j} binom(j,α)·Tr(L_{x^α})·u^α,
    # the Newton identities give m·C_m = Σ_{j=1}^m (-1)^{j-1}·P_j·C_{m-j}.
    # Tr(L_{x^α}) = τ·NF(x^α), where NF(x^α) = M[k]·NF(x^{α-e_k}), NF(1) = e_1.
    n = length(M)
    e₁ = zero_matrix(F, δ, 1)
    e₁[1, 1] = one(F)
    layer = Dict{Vector{Int},typeof(e₁)}(zeros(Int, n) => e₁)
    P = Vector{elem_type(S)}(undef, δ)
    for j in 1:δ
        next_layer = Dict{Vector{Int},typeof(e₁)}()
        ctx = MPolyBuildCtx(S)
        for (α, v) in layer
            for k in 1:n
                α′ = copy(α)
                α′[k] += 1
                haskey(next_layer, α′) && continue
                w = M[k] * v
                next_layer[α′] = w
                t = sum(τ[i] * w[i, 1] for i in 1:δ)
                iszero(t) && continue
                push_term!(ctx, _multinomial(α′) * t, [0; α′])
            end
        end
        P[j] = finish(ctx)
        layer = next_layer
    end
    C = Vector{elem_type(S)}(undef, δ + 1)
    C[1] = one(S)
    for m in 1:δ
        s = zero(S)
        for j in 1:m
            s += isodd(j) ? P[j] * C[m-j+1] : -P[j] * C[m-j+1]
        end
        C[m+1] = inv(F(m)) * s
    end
    # We return C(u_0,u) = Σ_m C_m(u)·u_0^{δ-m}, as C_m is homogeneous of degree m in u.
    u₀ = gen(S, 1)
    sum(C[m+1] * u₀^(δ - m) for m in 0:δ)
end
