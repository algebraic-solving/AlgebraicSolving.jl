export chandra

@doc Markdown.doc"""
    chandra(n::Int, characteristic::Int=0; c=QQ(51234, 100000))

Given a positive natural number `n` returns the Chandra ideal, a discretization of
Chandrasekhar's H-equation, generated by
$2n x_k - c x_k (1 + \sum_{i=1}^{n-1} \frac{k}{k+i} x_i) - 2n$ for $k \in \{1, \ldots, n\}$.
The parameter `c` is usually chosen as $0.51234$; over a finite field, its
denominator and $k+i$ must be invertible.

# Example
```jldoctest
julia> using AlgebraicSolving

julia> chandra(2)
QQMPolyRingElem[-25617//100000*x1^2 + 174383//50000*x1 - 4, -8539//25000*x1*x2 + 174383//50000*x2 - 4]
```
"""
function chandra(n::Int, characteristic::Int=0; c=QQ(51234, 100000))
    n >= 1 || throw(ArgumentError("Chandra systems require at least one variable."))

    if characteristic == 0
        R, _ = polynomial_ring(QQ, n, internal_ordering=:degrevlex)
    elseif is_probable_prime(characteristic)
        R, _ = polynomial_ring(GF(characteristic), n, internal_ordering=:degrevlex)
    else
        error("We only support finite fields or QQ as ground fields.")
    end

    return chandra(R, c=c)
end

@doc Markdown.doc"""
    chandra(R::MPolyRing; c=QQ(51234, 100000))

Returns the Chandra ideal in the given polynomial ring `R`, which must have at least one variable.

# Example
```jldoctest
julia> using AlgebraicSolving

julia> R, _ = QQ["x", "y"]
(Multivariate polynomial ring in 2 variables over QQ, QQMPolyRingElem[x, y])

julia> chandra(R, c=QQ(1, 2))
QQMPolyRingElem[-1//4*x^2 + 7//2*x - 4, -1//3*x*y + 7//2*y - 4]
```
"""
function chandra(R::MPolyRing; c=QQ(51234, 100000))
    CR = base_ring(R)
    vars = gens(R)
    polys = elem_type(R)[]
    n = nvars(R)
    n >= 1 || throw(ArgumentError("Chandra systems require at least one variable."))

    cq = QQ(c)
    den = CR(denominator(cq))
    (characteristic(CR) == 0 || !is_zero(den)) ||
        throw(ArgumentError("The denominator of c must be invertible in the base field."))
    cc = CR(numerator(cq)) // den

    for k in 1:n
        sum_poly = R(1)
        for i in 1:(n-1)
            d = CR(k + i)
            is_zero(d) && throw(ArgumentError("$(k + i) must be invertible in the base field."))
            sum_poly += (CR(k) // d) * vars[i]
        end
        push!(polys, CR(2*n) * vars[k] - cc * vars[k] * sum_poly - CR(2*n))
    end

    return Ideal(polys)
end
